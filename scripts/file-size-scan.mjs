/** Finds hand-written code/configuration files and counts their physical lines. */
import { lstat, readdir, readFile } from 'node:fs/promises';
import { basename, dirname, extname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const limit = 150;
const extensions = new Set([
  '.js',
  '.jsx',
  '.mjs',
  '.cjs',
  '.ts',
  '.tsx',
  '.css',
  '.scss',
  '.rs',
  '.py',
  '.sh',
  '.sql',
  '.html',
  '.json',
  '.toml',
  '.yaml',
  '.yml',
]);
const generatedDirectories = new Set([
  '.git',
  'node_modules',
  'dist',
  'coverage',
  'playwright-report',
  'test-results',
  'test-results-server',
  'target',
  '.vite',
  '.next',
  '__pycache__',
  '.claude',
]);
const inactivePaths = new Set(['legacy', 'services/calendar-companion/data']);
const generatedFiles = new Set([
  'package-lock.json',
  'Cargo.lock',
  // Generated by scripts/create-demo-backup.mjs; not hand-written configuration.
  'demo-workspace-backup.json',
]);

/** Project-relative path with forward slashes on every platform. */
export function projectPath(path) {
  return relative(projectRoot, path).split(sep).join('/');
}

async function collectFiles(path) {
  const info = await lstat(path);
  if (info.isSymbolicLink()) return [];
  if (info.isDirectory()) {
    const entries = await readdir(path, { withFileTypes: true });
    const children = entries
      .filter((entry) => !generatedDirectories.has(entry.name))
      .map((entry) => resolve(path, entry.name))
      .filter((child) => !inactivePaths.has(projectPath(child)));
    return (await Promise.all(children.map(collectFiles))).flat();
  }
  if (!extensions.has(extname(path)) || generatedFiles.has(basename(path))) {
    return [];
  }
  return [path];
}

function countLines(source) {
  const normalized = source.replace(/\r\n?/g, '\n');
  if (!normalized.length) return 0;
  return normalized.split('\n').length - Number(normalized.endsWith('\n'));
}

/** Returns the checked file count and every file over the limit, largest first. */
export async function measureFiles(targets) {
  const files = [...new Set((await Promise.all(targets.map(collectFiles))).flat())];
  const measured = await Promise.all(
    files.map(async (path) => ({
      path: projectPath(path),
      lines: countLines(await readFile(path, 'utf8')),
    })),
  );
  const violations = measured
    .filter(({ lines }) => lines > limit)
    .sort((a, b) => b.lines - a.lines || a.path.localeCompare(b.path));
  return { checked: files.length, violations };
}
