//! One signed S3 request (packet F1): path-style URL, host, payload hash, date and the
//! Signature V4 `Authorization` header.
use super::sigv4::{authorization, sha256_hex, Request};
use crate::config::media_settings::MediaConfig;
use std::{sync::OnceLock, time::Duration};
use time::OffsetDateTime;

fn client() -> &'static reqwest::Client {
    static CLIENT: OnceLock<reqwest::Client> = OnceLock::new();
    CLIENT.get_or_init(|| {
        reqwest::Client::builder()
            .timeout(Duration::from_secs(60))
            .connect_timeout(Duration::from_secs(5))
            .redirect(reqwest::redirect::Policy::none())
            .build()
            .expect("storage HTTP client starts")
    })
}

/// Storage keys are generated by the CRM (hex and `/`), so they need no encoding.
pub fn send(
    config: &MediaConfig,
    method: reqwest::Method,
    key: &str,
    body: Vec<u8>,
    content_type: Option<&str>,
) -> reqwest::RequestBuilder {
    let path = if key.is_empty() {
        format!("/{}", config.bucket)
    } else {
        format!("/{}/{key}", config.bucket)
    };
    let url = format!("{}{path}", config.endpoint);
    let host = url::Url::parse(&url)
        .ok()
        .and_then(|parsed| {
            let host = parsed.host_str()?.to_owned();
            Some(match parsed.port() {
                Some(port) => format!("{host}:{port}"),
                None => host,
            })
        })
        .unwrap_or_default();
    let now = OffsetDateTime::now_utc();
    let amz_date = format!(
        "{:04}{:02}{:02}T{:02}{:02}{:02}Z",
        now.year(),
        u8::from(now.month()),
        now.day(),
        now.hour(),
        now.minute(),
        now.second()
    );
    let payload_hash = sha256_hex(&body);
    let mut headers = vec![
        ("host", host),
        ("x-amz-content-sha256", payload_hash.clone()),
        ("x-amz-date", amz_date.clone()),
    ];
    if let Some(content_type) = content_type {
        headers.push(("content-type", content_type.to_owned()));
    }
    let signature = authorization(&Request {
        method: method.as_str(),
        path: &path,
        headers: &headers,
        payload_hash: &payload_hash,
        amz_date: &amz_date,
        region: &config.region,
        access_key: &config.access_key,
        secret_key: &config.secret_key,
    });
    let mut builder = client()
        .request(method, url)
        .header("authorization", signature);
    for (name, value) in headers.into_iter().filter(|(name, _)| *name != "host") {
        builder = builder.header(name, value);
    }
    builder.body(body)
}
