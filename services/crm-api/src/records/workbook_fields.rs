pub fn validate(collection: &str, payload: &Value) -> ApiResult<()> {
    let fields = match collection {
        "Clients" => CLIENT_FIELDS,
        "Properties" => PROPERTY_FIELDS,
        "Contacts" => CONTACT_FIELDS,
        _ => &[],
    };
    for field in fields {
        if matches!(payload.get(field), Some(Value::Array(_) | Value::Object(_))) {
            return Err(ApiError::invalid(
                "Workbook fields must contain scalar values.",
            ));
        }
    }
    Ok(())
}
